package main

//go:generate go run github.com/cilium/ebpf/cmd/bpf2go -type cache_stat bpf page_cache_obs.bpf.c -- -I/usr/include/bpf -O2 -g

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"os/signal"
	"syscall"
	"time"

	"github.com/cilium/ebpf/link"
	"github.com/cilium/ebpf/rlimit"
)

func main() {
	// 1. Remove Resource Limits
	// eBPF programs require the kernel to lock memory. The default limits are often too low.
	if err := rlimit.RemoveMemlock(); err != nil {
		log.Fatalf("Failed to remove memlock: %v", err)
	}

	// 2. Load the generated eBPF objects into the kernel
	// 'loadBpfObjects' is a function automatically generated by bpf2go!
	objs := bpfObjects{}
	if err := loadBpfObjects(&objs, nil); err != nil {
		log.Fatalf("Failed to load eBPF objects: %v", err)
	}
	defer objs.Close() // Ensure the eBPF program is cleaned up when our Go app exits

	// 3. Attach Probe 1: Total Cache Accesses
	// We tell the kernel to run 'trace_folio_access' whenever 'folio_mark_accessed' is called
	kprobeAccess, err := link.Kprobe("folio_mark_accessed", objs.TraceFolioAccess, nil)
	if err != nil {
		log.Fatalf("Failed to attach kprobe (folio_mark_accessed): %v", err)
	}
	defer kprobeAccess.Close()

	// 4. Attach Probe 2: Cache Misses (Disk I/O)
	// We tell the kernel to run 'trace_folio_miss' whenever 'filemap_add_folio' is called
	kprobeMiss, err := link.Kprobe("filemap_add_folio", objs.TraceFolioMiss, nil)
	if err != nil {
		log.Fatalf("Failed to attach kprobe (filemap_add_folio): %v", err)
	}
	defer kprobeMiss.Close()

	log.Println("Successfully loaded eBPF observer! Press Ctrl+C to exit.")
	log.Println("Waiting for events...")

	// 5. Setup Graceful Shutdown
	// We listen for Ctrl+C so we can exit cleanly and allow the 'defer' statements to run
	stopper := make(chan os.Signal, 1)
	signal.Notify(stopper, os.Interrupt, syscall.SIGTERM)

	// 6. Polling Loop: Read the BPF Map every 2 seconds
	ticker := time.NewTicker(2 * time.Second)
	defer ticker.Stop()

	for {
		select {
		case <-ticker.C:
			fmt.Println("--------------------------------------------------")
			fmt.Printf("%-16s | %-12s | %-12s\n", "PROCESS", "ACCESSES", "MISSES")
			fmt.Println("--------------------------------------------------")

			// Iterate over all entries in the 'CacheStats' map
			var key [16]byte
			var val bpfCacheStat // The Go struct auto-generated by bpf2go to match our C struct
			iterator := objs.CacheStats.Iterate()

			for iterator.Next(&key, &val) {
				// Convert the null-terminated C char array to a Go string
				processName := string(bytes.TrimRight(key[:], "\x00"))
				
				fmt.Printf("%-16s | %-12d | %-12d\n", processName, val.Accesses, val.Misses)
			}

			if err := iterator.Err(); err != nil {
				log.Printf("Error iterating map: %v", err)
			}

		case <-stopper:
			log.Println("Shutting down eBPF observer...")
			return
		}
	}
}
